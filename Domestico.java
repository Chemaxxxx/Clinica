package Clinica;

abstract class Domestico {
	protected String nombre;
	protected int edad;
	protected String raza;
	protected String chip;
	
	public Domestico(String nombre, int edad, String raza, String chip) {
		this.nombre = nombre;
		this.edad = edad;
		this.raza = raza;
		this.chip = chip;
	}
	
	

}
